"""번역 모델을 **이름 말고 성격으로** 고르게 한다.

## 왜 필요한가

설정 화면이 모델 이름만 늘어놓고 있었다.

    qwen2.5:14b
    huihui_ai/qwen2.5-vl-abliterated:7b
    llama3.1:8b

이걸 보고 무엇을 골라야 하는지 알 수가 없다. 사용자가 알고 싶은 것은
「한국어가 자연스러운 것」이나 「빠른 것」이지 이름이 아니다. 이름은 나중에
`ollama pull` 을 칠 때나 필요하다.

실제로 이름만 보고 `-vl`(그림 보는 판)을 골랐고, 그 모델이 우리 지시문을
번역해서 되돌려 줬다.

## 여기 적힌 것은 재어 본 값이 아니다

만드는 쪽에는 Ollama 도 그래픽카드도 없다. 아래 한 줄 평은 **모델을 만든 곳이
밝힌 것과 알려진 성격을 옮긴 것**이지 이 작품으로 돌려 본 결과가 아니다.

실제로 어느 것이 나은지는 `scripts/11_compare_translation.bat` 이 같은 원문으로
견줘 준다. 여기 적힌 것은 무엇부터 받아 볼지 고르는 데만 쓴다.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class 모델설명:
    """모델 하나. `이름` 이 아니라 `한마디` 가 먼저 보인다."""

    id: str          # `ollama pull` 에 쓰는 이름
    한마디: str       # 화면에서 제일 크게 보이는 줄
    설명: str         # 그 아래 한 줄
    GB: float        # 어림 크기. 받기 전에 「얼마나 받아야 하나」를 알려 준다

    @property
    def view(self) -> dict[str, object]:
        return {"id": self.id, "title": self.한마디, "note": self.설명, "gb": self.GB}


# 받아 볼 만한 것들. 12GB 짜리 카드에 들어가는 것만 골랐다.
#
# 순서가 곧 추천 순서다. 위에 있는 것부터 받아 보면 된다.
추천 = (
    모델설명(
        id="exaone3.5:7.8b",
        한마디="한국어가 가장 자연스럽습니다",
        설명="LG 가 한국어를 중심에 놓고 만든 것. 번역투가 적습니다",
        GB=4.8,
    ),
    모델설명(
        id="qwen2.5:7b",
        한마디="무난하고 시키는 대로 잘합니다",
        설명="줄 번호를 안 흐트러뜨립니다. 어느 쪽도 크게 모자라지 않습니다",
        GB=4.7,
    ),
    모델설명(
        id="gemma2:9b",
        한마디="문장이 매끄럽습니다",
        설명="구글이 만든 것. 조금 크고 조금 느립니다",
        GB=5.4,
    ),
    모델설명(
        id="aya-expanse:8b",
        한마디="여러 나라 말에 고르게 강합니다",
        설명="번역을 겨냥해 만든 것입니다",
        GB=5.1,
    ),
    모델설명(
        id="qwen2.5:14b",
        한마디="더 정확한 대신 많이 느립니다",
        설명="12GB 를 거의 다 씁니다. 시간이 넉넉할 때만",
        GB=9.0,
    ),
)

# 이름에 이 조각이 있으면 「거절 없음」으로 본다. 성인물에서는 이것이 크다
검열제거_자취 = ("abliterated", "abliterate", "uncensored", "dolphin")


def _바탕이름(이름: str) -> str:
    """`huihui_ai/qwen2.5-abliterated:7b` → `qwen2.5`.

    같은 알맹이를 여러 곳이 조금씩 손봐서 올려 둔다. 이름이 달라도 성격은
    같으므로, 아는 것을 붙여 주려면 바탕이 되는 이름을 봐야 한다.
    """
    글 = str(이름 or "").strip().lower()
    글 = 글.split("/")[-1]        # 올린 사람 이름 떼기
    글 = 글.split(":")[0]          # 태그 떼기
    for 자취 in 검열제거_자취:
        글 = 글.replace(f"-{자취}", "").replace(f"_{자취}", "")
    return 글.strip("-_")


def 검열없나(이름: str) -> bool:
    낮춘것 = str(이름 or "").lower()
    return any(자취 in 낮춘것 for 자취 in 검열제거_자취)


def _크기표(이름: str) -> str:
    """`qwen2.5:14b` → `14b`. 태그가 없으면 빈 글."""
    글 = str(이름 or "").strip().lower().split("/")[-1]
    return 글.split(":", 1)[1] if ":" in 글 else ""


def 설명찾기(이름: str) -> 모델설명 | None:
    """깔려 있는 모델에 아는 설명을 붙여 준다. 모르면 None.

    **크기표(`:14b`)를 먼저 맞춘다.** 예전에는 태그를 떼고 바탕 이름만 봐서
    `qwen2.5:14b` 에 `qwen2.5:7b` 의 설명이 붙었다. 화면에 「무난하고 시키는
    대로 잘합니다」 가 두 번 뜨고, 정작 「많이 느립니다」 는 안 떴다.
    크기가 다르면 성격도 다르다.
    """
    바탕 = _바탕이름(이름)
    if not 바탕:
        return None
    같은바탕 = [하나 for 하나 in 추천 if _바탕이름(하나.id) == 바탕]
    if not 같은바탕:
        return None
    내크기 = _크기표(이름)
    if 내크기:
        for 하나 in 같은바탕:
            if _크기표(하나.id) == 내크기:
                return 하나
    # 크기표가 없거나 아는 것 중에 그 크기가 없다. 바탕이 같으면 성격은 비슷하다
    return 같은바탕[0]


def 설명하기(이름: str, gb: float = 0.0) -> dict[str, object]:
    """화면에 그릴 한 덩이. 모르는 모델에도 무언가는 말해 준다.

    「모르는 모델입니다」 하고 마는 것은 도움이 안 된다. 크기만으로도
    빠른지 느린지는 말할 수 있다.
    """
    아는것 = 설명찾기(이름)
    if 아는것 is not None:
        한마디, 설명 = 아는것.한마디, 아는것.설명
    else:
        한마디 = "어떤 모델인지 모릅니다"
        설명 = (
            "직접 받아 두신 것입니다. "
            + ("작고 빠릅니다" if 0 < gb <= 5.5 else
               "크고 느립니다" if gb > 5.5 else "견줘 보고 판단해 주세요")
        )
    if 검열없나(이름):
        설명 = f"{설명} · 거절하지 않는 판입니다"
    return {"id": 이름, "title": 한마디, "note": 설명, "gb": round(gb, 1), "known": 아는것 is not None}


def 아직_없는것(깔린것: list[str]) -> list[dict[str, object]]:
    """추천 목록에서 아직 안 받은 것. 「이런 것도 있습니다」로 보여 준다."""
    있는바탕 = {_바탕이름(이름) for 이름 in 깔린것}
    return [하나.view for 하나 in 추천 if _바탕이름(하나.id) not in 있는바탕]
