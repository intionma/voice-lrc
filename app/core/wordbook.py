def 목록읽기() -> dict:
    """`{낱말: {일본어: 나올 말}, 끈말: [일본어]}`. 없거나 망가졌으면 기본값.

    **망가져 있어도 안 터진다.** 사전이 깨졌다고 번역을 통째로 못 하면 안 된다.
    """
    기본 = 기본목록()
    try:
        것 = json.loads(목록길().read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return 기본
    if not isinstance(것, dict):
        return 기본

    낱말 = 것.get("낱말")
    if not isinstance(낱말, dict):
        # 옛 판은 `{일본어: 한국어}` 를 통째로 적어 두었다. 그것도 읽어 준다 —
        # 판을 올렸다고 사용자가 적어 둔 것이 날아가면 안 된다
        낱말 = {} if ("낱말" in 것 or "끈말" in 것) else 것
    끈말 = 것.get("끈말")
    return {
        "낱말": {str(ja): str(ko) for ja, ko in 낱말.items() if str(ja).strip()},
        "끈말": [str(말) for 말 in 끈말 if str(말).strip()] if isinstance(끈말, list) else [],
    }


def 목록쓰기(목록: dict) -> Path:
    길 = 목록길()
    길.parent.mkdir(parents=True, exist_ok=True)
    # 쓰다 만 파일이 남으면 다음에 읽고 터진다. 다 쓰고 한 번에 바꿔 놓는다
    임시 = 길.with_suffix(".tmp")
    임시.write_text(json.dumps(목록, ensure_ascii=False, indent=2), encoding="utf-8")
    임시.replace(길)
    return 길


