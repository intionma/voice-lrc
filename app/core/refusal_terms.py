# ---- 표기 맞추기 ----
#
# 히라가나·가타카나·반각을 한 꼴로 맞춰서 본다. 그러면 낱말을 표기마다 따로
# 적을 일이 없다. **자리를 잃으면 안 된다** — 칠할 곳이 원래 글에서 어디인지
# 알아야 하므로 맞춘 글의 한 자리마다 원래 자리를 같이 든다.

# 받아쓰기가 아무 데나 끼워 넣는 것. 찾을 때만 뺀다
_빼는글자 = set("ー〜～♡♥❤・…‥ 　")
_탁점 = {"ﾞ", "ﾟ"}


def 맞춤(글: str) -> tuple[str, list[tuple[int, int]]]:
    """`(맞춘 글, 맞춘 글의 자리마다 원래 글의 [시작, 끝))`.

    끝까지 드는 까닭: 반각 `ﾎﾟ` 는 원래 두 글자인데 맞추면 `ぽ` 한 글자다.
    시작만 들면 칠할 때 `ﾟ` 가 떨어져 나간다.
    """
    난것: list[str] = []
    자리: list[tuple[int, int]] = []
    i = 0
    while i < len(글):
        조각 = 글[i]
        다음 = i + 1
        # 반각 가나는 탁점이 따로 온다(`ﾎﾟ`). 둘을 한 글자로 붙인다
        if 다음 < len(글) and 글[다음] in _탁점:
            조각 += 글[다음]
            다음 += 1
        for 글자 in unicodedata.normalize("NFKC", 조각):
            if 글자 in _빼는글자:
                continue
            if "ァ" <= 글자 <= "ヶ":
                글자 = chr(ord(글자) - 0x60)
            난것.append(글자.lower())
            자리.append((i, 다음))
        i = 다음
    return "".join(난것), 자리


def _맞춘말(말: str) -> str:
    return 맞춤(말)[0]


_ぱば = str.maketrans("ぱぴぷぺぽばびぶべぼ", "ばびぶべぼぱぴぷぺぽ")


def _갈래(것: 낱말, 짝있음: bool) -> list[tuple[str, str]]:
    """찾을 꼴들. `(맞춘 꼴, 종류)`.

    - 적은 말 그 자체
    - `っ` 를 뺀 꼴 — 받아쓰기가 작은 글자를 자주 흘린다 (`イっちゃう` → `イちゃう`)
    - `ぱ↔ば` 를 하나 바꾼 꼴 — 반탁점과 탁점을 자주 헷갈린다 (`ちんぽ` → `ちんぼ`)
    - 한자 말이면 그 읽기 — 받아쓰기가 가나로 적을 때. **소리가 같은 딴 말이
      있으면**(`子宮` = `至急`) 가나로 적힌 것은 어느 쪽인지 모르므로 「소리」 다
    """
    본꼴 = _맞춘말(것.말)
    난것 = [(본꼴, 표기)]
    가나만 = all("ぁ" <= 글자 <= "ゖ" for 글자 in 본꼴)
    if "っ" in 본꼴 and len(본꼴.replace("っ", "")) >= 3:
        난것.append((본꼴.replace("っ", ""), 표기))
    if 가나만:
        for 자리, 글자 in enumerate(본꼴):
            바뀐 = 글자.translate(_ぱば)
            if 바뀐 != 글자:
                난것.append((본꼴[:자리] + 바뀐 + 본꼴[자리 + 1:], 표기))
    읽기 = _맞춘말(것.읽기) if 것.읽기 else ""
    if 읽기 and 읽기 != 본꼴 and len(읽기) >= 3:
        난것.append((읽기, 소리 if 짝있음 else 표기))
    return 난것


# ---- 목록 → 찾개 ----

def 미성년말(목록: dict | None = None) -> list[낱말]:
    """1급 낱말. `minor_terms` 에서 **끈 것을 뺀 그대로**에 뜻만 붙이고,
    단서에만 쓰는 `미성년더함` 을 더한다."""
    목록 = 목록 if 목록 is not None else minor_terms.목록읽기()
    강한말, 약한말 = minor_terms.쓸말(목록)
    난것 = [낱말(말, 미성년뜻.get(말, "사용자가 더한 말"), 5,
              _미성년읽기.get(말, ""), 출처="미성년") for 말 in 강한말]
    난것 += [낱말(말, 미성년뜻.get(말, "사용자가 더한 말"), 5,
               _미성년읽기.get(말, ""), 약함=True, 출처="미성년") for 말 in 약한말]
    return 난것 + list(미성년더함)


def _목록열쇠(목록: dict) -> tuple:
    강한말, 약한말 = minor_terms.쓸말(목록)
    return (tuple(강한말), tuple(약한말), int(목록.get("나이") or minor_terms.기본나이))


