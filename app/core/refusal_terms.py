def _나이찾기(글: str, 나이한도: int) -> list[걸린것]:
    """나이를 말한 자리. ⚠ 가 쓰는 정규식을 **그대로** 쓴다."""
    난것 = []
    for 맞은것 in quality._AGE.finditer(글):
        if int(맞은것.group(1)) < 나이한도:
            난것.append(걸린것(맞은것.start(), 맞은것.end(), 맞은것.group(0),
                            f"{int(맞은것.group(1))}살", 5))
    for 맞은것 in quality._한자나이.finditer(글):
        나이 = quality._한자를수로(맞은것.group(1))
        if 나이 is not None and 나이 < 나이한도:
            난것.append(걸린것(맞은것.start(), 맞은것.end(), 맞은것.group(0),
                            f"{나이}살", 5))
    for 맞은것 in quality._가나나이.finditer(글):
        읽기 = 맞은것.group(0)
        나이 = quality._가나나이표[읽기]
        if 나이 < 나이한도:
            헷갈림 = 읽기 in quality._헷갈리는나이말
            난것.append(걸린것(
                맞은것.start(), 맞은것.end(), 읽기,
                f"{나이}살" + (" (딴 말과 소리가 같을 수 있음)" if 헷갈림 else ""),
                5, 약함=헷갈림))
    return 난것


def _학년찾기(글: str) -> list[걸린것]:
    난것 = []
    for 식, 뜻 in _학년식:
        for 맞은것 in 식.finditer(글):
            # `中二病`(중2병)은 학년이 아니라 허세 부리는 말버릇이다
            if 글[맞은것.end():맞은것.end() + 1] == "病":
                continue
            수 = 맞은것.group(1).translate(_숫자읽기)
            난것.append(걸린것(맞은것.start(), 맞은것.end(), 맞은것.group(0),
                            뜻.format(수), 5))
    return 난것


def _문장꼴찾기(글: str) -> list[걸린것]:
    난것 = []
    for 식, 뜻, 단계 in 기본문장꼴:
        for 맞은것 in re.finditer(식, 글):
            난것.append(걸린것(맞은것.start(), 맞은것.end(), 맞은것.group(0), 뜻, 단계,
                            쓴글=맞은것.group(0), 출처="문장"))
    return 난것


def _글로찾기(글: str, 찾개: _찾개) -> list[걸린것]:
    """AI 가 본 글에 있는 것 — 「그대로」 와 「표기」."""
    난것 = []
    if 찾개.그대로식 is not None:
        for 맞은것 in 찾개.그대로식.finditer(글):
            for 것 in 찾개.그대로표[맞은것.group(0)]:
                난것.append(걸린것(맞은것.start(), 맞은것.end(), 것.말, 것.뜻, 것.단계,
                                것.약함, 그대로, 맞은것.group(0), 것.출처))
    맞춘글, 자리 = 맞춤(글)
    if 찾개.꼴식 is not None:
        for 맞은것 in 찾개.꼴식.finditer(맞춘글):
            시작 = 자리[맞은것.start()][0]
            끝 = 자리[맞은것.end() - 1][1]
            쓴글 = 글[시작:끝]
            for 것, 종류 in 찾개.꼴표[맞은것.group(0)]:
                if 쓴글 == 것.말:
                    종류 = 그대로
                난것.append(걸린것(시작, 끝, 것.말, 것.뜻, 것.단계, 것.약함,
                                종류, 쓴글, 것.출처))
    return 난것


def _소리로찾기(글: str, 찾개: _찾개) -> list[걸린것]:
    """AI 가 본 글은 멀쩡한데 **소리가 같거나 비슷한** 것."""
    바꾼것 = _소리로(글)
    if 바꾼것 is None:
        return []
    읽기, 자리 = 바꾼것
    # **낱말이 시작하는 자리에서만** 맞춰 본다. 아무 데서나 보면 낱말 둘에
    # 걸친 소리(`製紙|工場` 의 `しこうじょ` ~ `しょうじょ`)가 닿는다
    시작들 = [i for i in range(len(읽기)) if i == 0 or 자리[i] != 자리[i - 1]]
    난것 = []
    길이들 = {len(r) for r in 찾개.소리표}
    for 길이 in sorted(길이들 | set(찾개.비슷길이), reverse=True):
        for 시작 in 시작들:
            if 시작 + 길이 > len(읽기):
                continue
            조각 = 읽기[시작:시작 + 길이]
            가 = 자리[시작][0]
            나 = 자리[시작 + 길이 - 1][1]
            for 것 in 찾개.소리표.get(조각, []):
                난것.append(걸린것(가, 나, 것.말, 것.뜻, 것.단계, 것.약함,
                                소리, 글[가:나], 것.출처))
            if 길이 not in 찾개.비슷길이:
                continue
            본것: set[str] = set()
            for i in range(길이):
                for 원래 in 찾개.비슷표.get(조각[:i] + "*" + 조각[i + 1:], ()):
                    if 원래 in 본것 or not _한끗(원래, 조각):
                        continue
                    본것.add(원래)
                    for 것 in 찾개.소리표[원래]:
                        난것.append(걸린것(가, 나, 것.말, 것.뜻, 것.단계, 것.약함,
                                        비슷한소리, 글[가:나], 것.출처))
    return 난것


# 너무 흔해서 거꾸로 찾지 않는 짝. `行く` 가 나올 때마다 「イク(절정)와 소리가
# 같음」 을 띄우면 단서 목록이 그것으로 덮인다
_흔한짝 = frozenset({"行く", "行っちゃう", "言っちゃう", "少々", "中立", "正規", "世紀"})


def _짝으로찾기(글: str, 찾개: _찾개) -> list[걸린것]:
    """짝표의 **딴 말이 적힌 자리.** `起こして` 가 적혔으면 `犯して` 를 잘못
    들은 것일 수도, 거꾸로 `犯して` 를 `起こして` 로 들은 것일 수도 있다.

    소리로 바꾸는 부품이 없어도 돈다 — 손으로 적은 짝이라서.
    """
    난것 = []
    for 딴말, 위험한것들 in _거꾸로짝.items():
        if 딴말 in _흔한짝:
            continue
        자리 = 글.find(딴말)
        while 자리 >= 0:
            for 위험, 같음 in 위험한것들:
                for 것 in 찾개.말표.get(위험, ()):
                    난것.append(걸린것(자리, 자리 + len(딴말), 것.말, 것.뜻, 것.단계,
                                    것.약함, 소리 if 같음 else 비슷한소리, 딴말, 것.출처))
            자리 = 글.find(딴말, 자리 + 1)
    return 난것


_종류차례 = {그대로: 0, 표기: 1, 소리: 2, 비슷한소리: 3}


def _안겹치게(것들: list[걸린것]) -> list[걸린것]:
    """겹치면 하나만 남긴다. `おちんちん` 안의 `ちんちん` 을 두 번 세지 않는다.

    고르는 차례: **AI 가 본 글에 있는 것**(그대로·표기)이 먼저, 그다음 긴 것,
    그다음 단계가 높은 것. 소리로 찾은 것은 글로 찾은 것과 겹치면 버린다 —
    글에 이미 그 말이 있는데 「소리가 같다」 고 또 말할 까닭이 없다.
    """
    남길것: list[걸린것] = []
    def 차례(x: 걸린것) -> tuple:
        소리로 = _종류차례[x.종류] >= 2
        # 소리로 찾은 것끼리는 **같은 소리가 비슷한 소리보다 먼저**다. 길이를
        # 먼저 보면 한 소리 다른 긴 말(`写生しちゃう` ~ `いっちゃう`)이
        # 소리가 똑같은 `写生` = `射精` 을 밀어낸다
        return (소리로, _종류차례[x.종류] if 소리로 else 0, -(x.끝 - x.시작),
                -x.단계, _종류차례[x.종류], x.시작)

    for 것 in sorted(것들, key=차례):
        if any(것.시작 < 남.끝 and 남.시작 < 것.끝 for 남 in 남길것):
            continue
        남길것.append(것)
    return sorted(남길것, key=lambda x: x.시작)


def 찾기(글: str, 목록: dict | None = None, *, 소리도: bool = True) -> list[걸린것]:
    """이 줄에서 걸릴 만한 자리를 모두. 약한말은 `약함` 이 켜진 채 1급으로 온다."""
    목록 = 목록 if 목록 is not None else minor_terms.목록읽기()
    나이한도 = int(목록.get("나이") or minor_terms.기본나이)
    찾개 = _찾개얻기(목록)
    것들 = (_글로찾기(글, 찾개) + _나이찾기(글, 나이한도)
           + _학년찾기(글) + _문장꼴찾기(글))
    if 소리도:
        것들 += _소리로찾기(글, 찾개) + _짝으로찾기(글, 찾개)
    return _안겹치게(것들)


def 미성년의심(글들: Iterable[str], 목록: dict | None = None) -> bool:
    """이 글들이 미성년 설정으로 의심되나. **⚠ 와 같은 규칙**에 단서용 말을 더한다.

    이것이 참이면 거절당한 묶음을 다시 보내지 않고 좁히지도 않는다. 더한 것
    (학년 꼴 · `미성년더함`)은 **다시 보내지 않는 쪽**으로만 움직인다 — ⚠ 수는
    그대로다.

    **소리로 찾은 것은 안 쓴다.** `自動`(자동)이 `児童`(아동)과 소리가 같다고
    다시 보내기를 막으면 안 된다.
    """
    목록 = 목록 if 목록 is not None else minor_terms.목록읽기()
    글들 = [str(글) for 글 in 글들]
    걸린말 = {말 for _, 말, _ in quality.find_minor_hints(
        [{"ja": 글, "start": 0.0} for 글 in 글들], 목록)}
    if quality.짚을까(걸린말, [], 목록):
        return True
    if any(_학년찾기(글) for 글 in 글들):
        return True
    찾개 = _찾개얻기(목록)
    더한강: set[str] = set()
    더한약: set[str] = set()
    for 글 in 글들:
        for 것 in _글로찾기(글, 찾개):
            if 것.출처 != "미성년더함":
                continue
            (더한약 if 것.약함 else 더한강).add(것.말)
    if 더한강:
        return True
    _, 약한말 = minor_terms.쓸말(목록)
    원래약 = 걸린말 & (set(약한말) | quality._헷갈리는나이말)
    return len(원래약 | 더한약) >= quality.약한말겹침


# 받아쓰기가 이보다 자신 없으면 「잘못 받아적었을 수 있음」 으로 짚는다.
# ⚠ 쪽의 기준(`quality.LOW_CONFIDENCE`)을 그대로 쓴다
자신없음 = quality.LOW_CONFIDENCE


def _짝들(말: str) -> list[dict[str, Any]]:
    return [{"word": 딴, "gloss": 뜻, "same": 같음} for 딴, 뜻, 같음 in 소리짝.get(말, [])]


def 단서(줄들: list[dict[str, Any]], 목록: dict | None = None) -> dict[str, Any]:
    """거절당한 묶음의 단서를 모은다. **화면에 그대로 보여 줄 모양**으로.

    `줄들` 은 `{index, ja, sent?, avg_logprob?, culprit?, ...}`. `ja` 는 받아쓴 그대로,
    `sent` 는 실제로 나간 글(가린 뒤)이다. 둘이 다르면 그 낱말은 가려져
    나갔으므로 AI 가 보지 못했다 — 단서로서 힘이 약하다.

    걸린 것이 없어도 받아쓰기가 자신 없거나, 망가졌거나, **전에 사람이 고친
    적 있는 말**이 든 줄은 넣는다. 그런 줄이 엉뚱한 말로 읽혀 막혔을 수 있다.
    """
    목록 = 목록 if 목록 is not None else minor_terms.목록읽기()
    의심 = 미성년의심((줄.get("ja", "") for 줄 in 줄들), 목록)
    고친것 = asr_fixes.짝들()

    보일것 = []
    for 줄 in 줄들:
        글 = str(줄.get("ja", ""))
        보낸글 = str(줄.get("sent", 글))
        걸림 = []
        for 것 in 찾기(글, 목록):
            단계 = 것.단계 if not 것.약함 or 의심 else 2
            글로 = 것.종류 in 글로찾음
            걸림.append({
                "start": 것.시작, "end": 것.끝, "term": 것.말, "gloss": 것.뜻,
                "level": 단계, "level_name": 단계이름[단계],
                # 화면에는 이것이 나간다. 1급이 가장 세다
                "grade": 급(단계),
                "kind": 것.종류,
                "written": 것.쓴글 or 것.말,
                # 가려서 나갔으면 AI 는 이 말을 못 봤다
                "masked": 글로 and (것.쓴글 or 것.말) not in 보낸글,
                # 소리가 같은 딴 말 — 받아쓰기가 잘못 들었을 수 있다
                "pairs": _짝들(것.말) if 글로 else [],
            })
        배운것 = [
            {"wrong": 틀린, "right": 고친, "count": 수}
            for 틀린, 고친, 수 in 고친것 if len(틀린) >= 2 and 틀린 in 글
        ]
        자신 = 줄.get("avg_logprob")
        흐림 = 자신 is not None and float(자신) < 자신없음
        망가짐 = garbage.why_broken(글)
        # 「좁히기」 가 찾아낸 줄은 걸린 낱말이 없어도 넣는다. 그쪽이 증거다
        막힌줄 = bool(줄.get("culprit"))
        if not (걸림 or 흐림 or 망가짐 or 막힌줄 or 배운것):
            continue
        보일것.append({
            **{k: v for k, v in 줄.items() if k not in ("sent",)},
            "hits": 걸림,
            # AI 가 본 글에서 가장 센 것. 소리로만 닿은 것은 따로 센다
            "top": max((h["level"] for h in 걸림 if h["kind"] in 글로찾음), default=0),
            "top_sound": max((h["level"] for h in 걸림 if h["kind"] not in 글로찾음),
                             default=0),
            "unsure": 흐림,
            "broken": 망가짐,
            "learned": 배운것,
        })

    # 막힌 줄이 먼저, 그다음 AI 가 본 글에서 센 것부터, 그다음 소리로 닿은 것.
    # 같으면 번호 차례 — 사용자가 프롬프트에서 찾아가기 쉽다
    보일것.sort(key=lambda 줄: (not 줄.get("culprit"), -줄["top"], -줄["top_sound"],
                              int(줄.get("index", 0))))
    return {
        "lines": 보일것,
        "top": max((줄["top"] for 줄 in 보일것), default=0),
        "minor": 의심,
        "count": len(줄들),
        # 소리 비교 부품이 없으면 그 갈래는 빠졌다. 화면이 말해 준다
        "sound": 소리비교되나(),
    }
