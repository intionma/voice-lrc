"""클립보드에서 온 글이 **우리 답인가**.

앱 상태를 안 본다. 글 하나와 「지금 무엇을 기다리는가」만 받아서 판정을
돌려준다. 그래야 시험에서 벤더별 복사 출력을 그대로 넣어 볼 수 있다.

## 왜 순수 함수인가

클립보드를 계속 훔쳐보는 구조는 **이 설계에서 제일 먼저 무너질 곳이다.**
사람은 하루에 수십 번 아무거나 복사한다 — 카톡 글, 주소, 일본어 원문,
방금 우리가 내준 프롬프트. 그중 하나라도 답으로 잘못 받으면 자막이 조용히
망가진다. 오류도 안 나고, 줄도 안 빠지고, 들어 보기 전에는 모른다.

그래서 「받는다」는 판단을 앱에서 떼어내 여기 한 군데로 모은다. 여기만
시험하면 되고, 여기만 보면 왜 안 받았는지 알 수 있다.

## 네 번 거른다

    1. 모양     `번호<구분><글>` 이 세 줄 이상인가
    2. 주인     그 번호들이 기다리는 트랙의 칸 안에 있는가
    3. 메아리   방금 우리가 내준 프롬프트가 그대로 돌아온 것 아닌가
    4. 말       한국어인가 — 일본어가 그대로 오면 안 받는다

## 일본어를 세 겹으로 막는다

원문이 그대로 돌아오는 일이 잦다. 모델이 「번역해 달라」를 못 알아듣거나,
사용자가 복사할 것을 헷갈렸거나, 우리가 낸 프롬프트를 다시 복사했거나.

    가) 앱이 쓴 것 기억    우리가 낸 글과 같으면 메아리다
    나) 원문 대조          그 번호에 우리가 넣어 준 원문과 같은 줄
    다) 가나 대 한글       줄에 가나가 있고 한글이 없으면 안 옮긴 줄

**「가나가 있으면 일본어」가 아니다.** 한국어 번역에도 고유명사가 가나로
남는다(「あかり 는 웃었다」). 그래서 **가나가 있고 한글이 없을 때만** 안
옮긴 줄로 본다.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Iterable

from . import exchange

# 이만큼은 번호 줄이 있어야 답으로 본다. 두 줄짜리는 우연히 맞을 수 있다 —
# 「1. 사과」 「2. 배」 같은 메모가 실제로 걸렸다
최소줄수 = 3

# 번호가 붙은 줄이 전체에서 이만큼은 돼야 한다. 긴 글에 번호 몇 줄이 섞인
# 것(회의록·목차)을 답으로 받지 않는다
최소비율 = 0.5

# 가나. 히라가나 · 가타카나 · 반각 가타카나
_가나 = re.compile(r"[ぁ-ゟ゠-ヿｦ-ﾝ]")
# 한글 낱자와 음절
_한글 = re.compile(r"[가-힣ᄀ-ᇿ㄰-㆏]")


def 가나있나(글: str) -> bool:
    return bool(_가나.search(글))


def 한글있나(글: str) -> bool:
    return bool(_한글.search(글))


def 안옮긴줄인가(글: str) -> bool:
    """가나가 있고 한글이 없으면 안 옮긴 줄이다.

    한국어 번역에도 고유명사가 가나로 남을 수 있으므로(「あかり 는 웃었다」)
    가나가 있다는 것만으로는 안 된다.
    """
    return 가나있나(글) and not 한글있나(글)


@dataclass(frozen=True)
class 기다리는것:
    """지금 답을 기다리는 트랙 하나. **앱의 물건을 그대로 넘기지 않는다.**"""

    열쇠: str
    # 이 트랙에 떼어 준 번호 칸 `[시작, 끝)`
    칸시작: int
    칸끝: int
    # 우리가 내준 원문 `{번호: 일본어}`. 대조에 쓴다. 없으면 그 겹은 건너뛴다
    내준원문: dict[int, str] = field(default_factory=dict)


@dataclass(frozen=True)
class 판정:
    """받을 것인가, 아니면 왜 안 받는가."""

    받는다: bool
    주인: str = ""
    까닭: str = ""
    # 사람에게 보여 줄 한 줄. 받지 않을 때만 채운다
    말: str = ""
    줄수: int = 0

    def __bool__(self) -> bool:
        return self.받는다


def _칸안인가(번호: int, 것: 기다리는것) -> bool:
    return 것.칸시작 <= 번호 < 것.칸끝


def 보기(
    글: str,
    기다림: Iterable[기다리는것],
    *,
    우리가낸것: Iterable[str] = (),
) -> 판정:
    """클립보드 글을 판정한다. **아무것도 안 바꾼다.**

    `우리가낸것` 은 방금 복사 단추로 내보낸 글들이다. 그것이 그대로 돌아오면
    사용자가 복사한 것을 다시 복사했거나 붙여넣기를 잘못한 것이다.
    """
    글 = (글 or "").strip()
    if not 글:
        return 판정(False, 까닭="빈글")

    # ── 3. 메아리 ── 값싼 검사부터 한다
    for 낸것 in 우리가낸것:
        if 낸것 and 글 == 낸것.strip():
            return 판정(False, 까닭="메아리",
                       말="방금 복사한 것이 그대로 돌아왔습니다. 넣지 않았습니다.")

    # ── 1. 모양 ──
    줄들 = exchange.번호줄(글)
    if len(줄들) < 최소줄수:
        return 판정(False, 까닭="모양", 줄수=len(줄들))

    글줄수 = len([줄 for 줄 in 글.splitlines() if 줄.strip()])
    if 글줄수 and len(줄들) / 글줄수 < 최소비율:
        # 긴 글에 번호 몇 줄이 섞인 것. 회의록·목차가 실제로 걸렸다
        return 판정(False, 까닭="섞인글", 줄수=len(줄들))

    # ── 2. 주인 ── 번호가 어느 칸에 제일 많이 들어가는가
    후보 = list(기다림)
    if not 후보:
        return 판정(False, 까닭="기다리는것없음")

    셈: dict[str, int] = {}
    for 번호, _ in 줄들:
        for 것 in 후보:
            if _칸안인가(번호, 것):
                셈[것.열쇠] = 셈.get(것.열쇠, 0) + 1
    if not 셈:
        return 판정(False, 까닭="남의번호", 줄수=len(줄들),
                   말="번호가 지금 기다리는 트랙의 것이 아닙니다. 넣지 않았습니다.")

    열쇠 = max(셈, key=lambda k: 셈[k])
    주인 = next(것 for 것 in 후보 if 것.열쇠 == 열쇠)
    내것 = [(n, t) for n, t in 줄들 if _칸안인가(n, 주인)]

    # ── 4. 말 ── 일본어가 그대로 온 것 아닌가
    #
    # **한 줄만 보고 되돌리지 않는다.** 고유명사가 가나로 남은 줄이 하나쯤
    # 있는 것은 정상이다. 절반을 넘으면 통째로 안 옮겨진 것으로 본다
    안옮김 = sum(1 for _, t in 내것 if 안옮긴줄인가(t))
    if 안옮김 * 2 > len(내것):
        return 판정(False, 까닭="일본어", 줄수=len(내것),
                   말="번역이 아니라 일본어가 그대로 온 것 같습니다. 넣지 않았습니다.")

    # 우리가 내준 원문과 **글자까지 똑같은** 줄이 절반을 넘으면 원문 그대로다.
    # 가나 검사만으로는 못 잡는 것이 있다 — 한자만으로 된 줄에는 가나가 없다
    if 주인.내준원문:
        같은것 = sum(
            1 for n, t in 내것
            if (원 := 주인.내준원문.get(n)) and t.strip() == 원.strip()
        )
        if 같은것 * 2 > len(내것):
            return 판정(False, 까닭="원문그대로", 줄수=len(내것),
                       말="보낸 원문이 그대로 돌아왔습니다. 넣지 않았습니다.")

    return 판정(True, 주인=열쇠, 줄수=len(내것))
