@functools.lru_cache(maxsize=1)
def _읽개():
    """pykakasi. 없으면 None — 소리 비교만 빠지고 나머지는 돈다."""
    try:
        import pykakasi
    except ImportError:
        return None
    try:
        return pykakasi.kakasi()
    except Exception:      # noqa: BLE001 — 사전이 망가졌어도 앱은 돌아야 한다
        return None


def 소리비교되나() -> bool:
    return _읽개() is not None


def _소리로(글: str) -> tuple[str, list[tuple[int, int]]] | None:
    """`(읽기, 읽기 자리마다 원래 글의 [시작, 끝))`. 못 하면 None.

    한 조각(낱말 하나쯤)의 읽기는 그 조각 전체를 가리킨다. 소리로 찾은 것을
    칠할 때 조각째로 칠하는 까닭이다.
    """
    읽개 = _읽개()
    if 읽개 is None:
        return None
    try:
        조각들 = 읽개.convert(글)
    except Exception:      # noqa: BLE001
        return None
    읽기: list[str] = []
    자리: list[tuple[int, int]] = []
    시작 = 0
    for 조각 in 조각들:
        원래 = str(조각.get("orig", ""))
        끝 = 시작 + len(원래)
        for 글자 in _맞춘말(str(조각.get("hira", ""))):
            읽기.append(글자)
            자리.append((시작, 끝))
        시작 = 끝
    return "".join(읽기), 자리


def _한끗(가: str, 나: str) -> bool:
    """길이가 같고 한 소리만 다른가.

    **`っ` 하나 차이는 안 센다.** `いしちゃう` ~ `いっちゃう` 처럼 아무 말이나
    `〜っちゃう` 꼴로 닿아 버린다.
    """
    다른것 = [(x, y) for x, y in zip(가, 나) if x != y]
    return (len(가) == len(나) and len(다른것) == 1
            and "っ" not in 다른것[0])


