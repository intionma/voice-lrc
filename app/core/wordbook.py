def 표(번호: int) -> str:
    return f"{표머리}{번호:02d}"


def 받침있나(글자: str) -> bool:
    """한글 한 글자에 받침이 있나. 한글이 아니면 있는 것으로 친다.

    모르면 받침이 있는 쪽으로 잡는다. 「자지을」 은 어색하지만 「고추를」 을
    「고추을」 로 만드는 것보다는 덜 틀린다 — 라고 하기 어렵다. 다만 숫자나
    라틴 글자로 끝나는 낱말은 대개 받침처럼 읽는다.
    """
    if not 글자:
        return True
    코드 = ord(글자[-1])
    if not (0xAC00 <= 코드 <= 0xD7A3):
        return True
    return (코드 - 0xAC00) % 28 != 0


def _받침이ㄹ인가(글자: str) -> bool:
    """`으로`/`로` 는 ㄹ 받침이 예외다 — 「하늘로」 지 「하늘으로」 가 아니다."""
    if not 글자:
        return False
    코드 = ord(글자[-1])
    if not (0xAC00 <= 코드 <= 0xD7A3):
        return False
    return (코드 - 0xAC00) % 28 == 8      # 8 = ㄹ


def 조사맞추기(앞말: str, 조사: str) -> str:
    """앞말 끝소리에 맞는 조사를 돌려준다. 모르는 조사는 그대로."""
    for 받침용, 민낯용 in 조사짝:
        if 조사 not in (받침용, 민낯용):
            continue
        if (받침용, 민낯용) == ("으로", "로"):
            # ㄹ 받침은 `로` 를 쓴다
            return "로" if (not 받침있나(앞말) or _받침이ㄹ인가(앞말)) else "으로"
        return 받침용 if 받침있나(앞말) else 민낯용
    return 조사


def 가릴낱말찾기(글: str, 사전: dict[str, str]) -> list[str]:
    """이 글에 나오는, 적어 둔 낱말들. **긴 것부터.**

    `おちんぽ` 와 `ちんぽ` 가 둘 다 사전에 있으면 긴 쪽을 먼저 가려야 한다.
    짧은 쪽을 먼저 가리면 `おKW01` 이 되어 `お` 가 남는다.
    """
    return sorted((ja for ja in 사전 if ja and ja in 글), key=len, reverse=True)


def 가리기(글: str, 사전: dict[str, str],
        표맵: dict[str, str] | None = None) -> tuple[str, dict[str, str]]:
    """적어 둔 낱말을 표로 바꾼다. `(가린 글, {표: 일본어})`.

    `표맵` 을 넘기면 **이어서 번호를 매긴다.** 묶음이 여럿이어도 같은 낱말은
    늘 같은 표가 되어야, 사람이 여러 창에 나눠 돌려도 헷갈리지 않는다.
    """
    쓴것 = dict(표맵 or {})
    이미준것 = {ja: 표 for 표, ja in 쓴것.items()}
    난것 = 글
    for ja in 가릴낱말찾기(글, 사전):
        # **긴 낱말이 이미 먹었으면 건너뛴다.** `膣内射精` 을 가리고 나면
        # `膣内`·`射精`·`膣` 은 글에 남아 있지 않은데, 그래도 번호를 하나씩
        # 내주고 있었다. 한 줄에 번호를 넷씩 태우고, 나간 적 없는 표가 표맵에
        # 쌓여서 **번역기가 지어낸 번호를 지어낸 줄 모르고 되돌린다**
        if ja not in 난것:
            continue
        붙일표 = 이미준것.get(ja)
        if 붙일표 is None:
            붙일표 = 표(len(쓴것) + 1)
            쓴것[붙일표] = ja
            이미준것[ja] = 붙일표
        난것 = 난것.replace(ja, 붙일표)
    return 난것, 쓴것


def 표들(글: str) -> list[str]:
    """글에 든 표를 찾은 차례로. `KW1`·`kw 01` 도 `KW01` 로 맞춰서 준다."""
    return [표(int(번호)) for 번호 in _표찾기.findall(글)]


def 나올말(ja: str, 사전: dict[str, str]) -> str:
    """이 일본어 낱말 자리에 무엇이 나와야 하나.

    **빈 값이면 일본어 그대로다.** 「모른다」는 상태가 아니라 「그대로 두겠다」
    는 뜻이다 — 앱은 적어 둔 낱말만 가리므로 모를 일이 없다.
    """
    return 사전.get(ja, "") or ja


