"""미성년 설정이 의심되는 낱말 목록. **사용자가 고치고 늘릴 수 있다.**

## 왜 파일로 빼나

낱말을 코드에 박아 두면 헛걸림이 나도 사용자가 손을 못 댄다. `少年` 은 성인
남성한테도 쓰고 `美少女` 는 갈래 이름으로도 흔해서, 이런 것이 매번 뜨면
사람이 ⚠ 를 아예 안 보게 된다. **그것이 제일 나쁘다** — 진짜 걸려야 할 때
못 잡는다.

그래서 목록을 `설정폴더/위험낱말.json` 으로 빼고, 끄거나 더할 수 있게 한다.
**기본으로 되돌리기**가 늘 있어야 한다 — 잘못 지워 놓고 못 돌아오면 안 된다.

## 강한말과 약한말

같은 무게로 두면 낱말을 늘릴수록 헛걸림만 는다.

    강한말   혼자서도 짚는다. `ランドセル`(초등생 책가방)처럼 거의 확정인 것
    약한말   **둘 이상 겹쳐야** 짚는다. `教室`·`放課後` 는 하나로는 아무 뜻이
             없지만 여럿이 겹치면 학교 배경이다

`dlsite.py` 가 상품 태그를 이미 `MINOR_GENRES` / `MINOR_GENRES_STRONG` 로
갈라 두었다. 그 결을 따른다.

## 가나 표기를 빠뜨리면 안 된다

**여기가 진짜 구멍이었다.** 받아쓰기는 글이 아니라 **말소리**를 적는다.
`小学生` 이라고 말해도 `しょうがくせい` 로 적힐 수 있다. 한자만 보면 그런
트랙을 통째로 놓친다.
"""

from __future__ import annotations

import json
from pathlib import Path

# 혼자서도 짚는 말. 이것 하나면 확인할 값어치가 있다
기본강한말: tuple[str, ...] = (
    # 초등
    "小学生", "小学校", "小学", "ランドセル",
    "しょうがくせい", "しょうがっこう",
    # 중등
    "中学生", "中学校", "ちゅうがくせい", "ちゅうがっこう",
    # 고등 — 일본 고교생은 15~18세라 대개 미성년이다
    "高校生", "女子高生", "男子高生", "こうこうせい", "じょしこうせい",
    # 갈래에서 쓰는 줄임말. **JK 만 있고 JS·JC 가 빠져 있었다** — 셋이 세트다
    "JK", "JC", "JS", "ＪＫ", "ＪＣ", "ＪＳ",
    "女子小学生", "女子中学生",
    # 유아
    "幼稚園", "保育園", "園児", "ようちえん", "ほいくえん",
    # 갈래말
    "ロリ", "ろり", "幼女", "ようじょ",
    # **ショタ 가 빠져 있었다.** ロリ 의 반대짝이다
    "ショタ", "しょた",
    # `ロリコン`·`ショタコン` 은 따로 안 적어도 된다 — `ロリ`·`ショタ` 가
    # 안에 들어 있어서 글자로 걸린다
)

# 「어린 + 아이」를 **붙여서** 잡는다.
#
# 낱말로 잘라서 약한말에 넣으면 안 된다. `小さい` 도 `女の子` 도 어른 나오는
# 작품에 흔해서, 둘을 따로 세면 「小さい声で言う女の子」(어른) 가 걸린다.
# **붙어 있을 때만** 뜻이 분명하다.
_어린 = ("小さい", "小さな", "ちっちゃい", "ちっちゃな", "幼い", "おさない")
_아이 = ("女の子", "男の子", "子", "おんなのこ", "おとこのこ")
기본강한말 += tuple(앞 + 뒤 for 앞 in _어린 for 뒤 in _아이)

# 둘 이상 겹쳐야 짚는 말. 하나로는 아무 뜻이 없다
기본약한말: tuple[str, ...] = (
    "少年", "美少女", "児童", "子供", "こども",
    # 혼자서는 어른한테도 쓴다. 딴 것과 겹칠 때만 뜻이 있다
    "女の子", "男の子",
    "制服", "セーラー服", "体操服", "スク水", "スクール水着",
    "放課後", "教室", "担任", "保健室", "通学", "同級生", "クラスメイト",
    "年生", "ねんせい",
)

# 이 나이 아래가 나오면 짚는다
기본나이 = 18


def 목록길() -> Path:
    from app.core import settings as settings_store

    return settings_store.config_dir() / "위험낱말.json"


def 기본목록() -> dict:
    return {
        "강한말": list(기본강한말),
        "약한말": list(기본약한말),
        "끈말": [],
        "나이": 기본나이,
    }


def 목록읽기() -> dict:
    """`{강한말, 약한말, 끈말, 나이}`. 없거나 망가졌으면 기본값.

    **망가져 있어도 안 터진다.** 그리고 **못 읽으면 기본값으로 돈다** — 목록이
    깨졌다고 검사를 통째로 건너뛰면, 잡아야 할 것을 조용히 놓친다.
    """
    기본 = 기본목록()
    try:
        것 = json.loads(목록길().read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return 기본
    if not isinstance(것, dict):
        return 기본

    난것 = dict(기본)
    for 칸 in ("강한말", "약한말", "끈말"):
        값 = 것.get(칸)
        if isinstance(값, list):
            난것[칸] = [str(말) for 말 in 값 if str(말).strip()]
    나이 = 것.get("나이")
    if isinstance(나이, int) and 0 < 나이 <= 30:
        난것["나이"] = 나이
    return 난것


def 목록쓰기(목록: dict) -> Path:
    길 = 목록길()
    길.parent.mkdir(parents=True, exist_ok=True)
    # 쓰다 만 파일이 남으면 다음에 읽고 터진다. 다 쓰고 한 번에 바꿔 놓는다
    임시 = 길.with_suffix(".tmp")
    임시.write_text(json.dumps(목록, ensure_ascii=False, indent=2), encoding="utf-8")
    임시.replace(길)
    return 길


def 되돌리기() -> dict:
    """기본 목록으로 돌린다. **잘못 지워 놓고 못 돌아오면 안 된다.**"""
    기본 = 기본목록()
    목록쓰기(기본)
    return 기본


def 쓸말(목록: dict) -> tuple[list[str], list[str]]:
    """`(강한말, 약한말)` — 꺼 둔 것을 뺀 나머지.

    **끈 것은 지운 것이 아니다.** 헛걸림이 나서 잠깐 빼 두었을 뿐이라, 목록에는
    남아 있어야 다시 켤 수 있다.
    """
    끈것 = set(목록.get("끈말") or [])
    강 = [말 for 말 in (목록.get("강한말") or []) if 말 and 말 not in 끈것]
    약 = [말 for 말 in (목록.get("약한말") or []) if 말 and 말 not in 끈것]
    return 강, 약


# 1~19 를 한자로. 나이를 설명할 때 쓴다 — 그보다 큰 수는 쓸 일이 없다
_한자낱글자 = "〇一二三四五六七八九"


def 한자로(수: int) -> str:
    """`17` → `十七`. 1~19 밖이면 숫자 그대로.

    **예시가 틀리면 설명이 없느니만 못하다.** 나이 한도를 바꿨는데 예시가
    그대로면, 그것을 보고 「20살도 잡히나?」 하고 잘못 배운다.
    """
    if not 1 <= 수 <= 19:
        return str(수)
    if 수 < 10:
        return _한자낱글자[수]
    return "十" + (_한자낱글자[수 - 10] if 수 > 10 else "")


def 전각으로(수: int) -> str:
    """`17` → `１７`. 이것도 잡는다는 것을 보여 주려고 쓴다."""
    return str(수).translate(str.maketrans("0123456789", "０１２３４５６７８９"))


# ---- 숫자까지 가나로 말한 나이 ----
#
# 받아쓰기는 글이 아니라 **말소리**를 적는다. `十七歳` 라고 말해도
# `じゅうななさい` 로 적힐 수 있고, 그러면 한자도 숫자도 없어서 통째로 놓친다.
#
# **규칙으로 못 만든다.** 세는 말이 숫자와 붙으면서 소리가 바뀐다 —
# `いち`+`さい` 는 `いっさい`, `はち`+`さい` 는 `はっさい`, `じゅう`+`さい` 는
# `じゅっさい`. 그래서 표로 만든다.

# 홑자리. 한 수에 읽는 법이 둘인 것이 있다 (7 = なな·しち)
_홑소리 = {
    1: ("いっ",), 2: ("に",), 3: ("さん",), 4: ("よん",), 5: ("ご",),
    6: ("ろく",), 7: ("なな", "しち"), 8: ("はっ", "はち"), 9: ("きゅう",),
}

# 열자리
_열소리 = {
    1: "じゅう", 2: "にじゅう", 3: "さんじゅう", 4: "よんじゅう", 5: "ごじゅう",
    6: "ろくじゅう", 7: "ななじゅう", 8: "はちじゅう", 9: "きゅうじゅう",
}

# 딱 떨어지는 열 (10·20·30…). `じゅう` 가 `じゅっ`·`じっ` 로 바뀐다
_열끝소리 = ("じゅっ", "じっ")

# **넣으면 안 되는 것.** 흔한 딴 말과 소리가 똑같다.
#
#   いっさい = 一切 (전혀·일절)    じっさい = 実際 (실제)
#   くさい   = 臭い (냄새난다)
#
# 이런 것을 넣으면 아무 작품에서나 ⚠ 가 뜬다. 그러면 사람이 ⚠ 를 아예 안 보게
# 되고, 그것이 못 잡는 것보다 나쁘다. 9살은 `くさい` 를 빼도 `きゅうさい` 로
# 잡히고, 10살은 `じっさい` 를 빼도 `じゅっさい` 로 잡힌다. **1살만 못 잡는데,
# 그건 이 바닥에 없는 설정이다.**
안쓰는나이말 = frozenset({"いっさい", "じっさい", "くさい"})

# **혼자서는 안 짚는 것.** 딴 말 속에 묻어 나올 수 있다.
#
#   にさい   ← 「〜に最高」(にさいこう)   さんさい ← 「お母さん最高」
#   ごさい   ← 「〜ご最高」               きゅうさい ← 救済
#
# 빼기에는 아깝고 혼자 짚기에는 위험해서 약한말로 둔다 — 딴 것과 겹쳐야 뜬다.
_헷갈리는홑수 = (2, 3, 5, 9)


def 가타카나로(글: str) -> str:
    """`じゅうななさい` → `ジュウナナサイ`. 받아쓰기가 가타카나로 뱉기도 한다."""
    return "".join(
        chr(ord(글자) + 0x60) if "ぁ" <= 글자 <= "ゖ" else 글자 for 글자 in 글
    )


def _소리들(수: int) -> list[str]:
    """`17` → `['じゅうなな', 'じゅうしち']`. 세는 말은 안 붙인 상태."""
    열, 홑 = divmod(수, 10)
    앞 = _열소리.get(열, "")
    if 홑 == 0:
        # `じゅう` 를 떼고 `じゅっ`·`じっ` 를 붙인다
        return [앞[:-3] + 끝 for 끝 in _열끝소리]
    return [앞 + 소리 for 소리 in _홑소리[홑]]


def 가나나이표() -> dict[str, int]:
    """`{'じゅうななさい': 17, ...}`. 1~99 를 다 만든다.

    **어른 나이까지 만들어야 한다.** 18·20 을 빼 두면 `じゅうはっさい`(18살)
    안의 `はっさい`(8살) 가 걸려서 **어른이 미성년으로 잡힌다.** 한자에서
    `十八歳` 안의 `八歳` 가 걸리던 것과 똑같은 사고다. 표에 있어야 긴 것부터
    맞춰 보면서 통째로 집어삼킨다.
    """
    표: dict[str, int] = {}
    for 수 in range(1, 100):
        for 소리 in _소리들(수):
            읽기 = 소리 + "さい"
            if 읽기 in 안쓰는나이말:
                continue
            표[읽기] = 수
            표[가타카나로(읽기)] = 수
    return 표


def 가나로(수: int) -> str:
    """`17` → `じゅうななさい`. 설명에 보기로 쓴다. 없으면 빈 글."""
    if not 1 <= 수 <= 99:
        return ""
    쓸것 = [소리 + "さい" for 소리 in _소리들(수)
           if 소리 + "さい" not in 안쓰는나이말]
    return 쓸것[0] if 쓸것 else ""


def 헷갈리는나이말() -> frozenset[str]:
    """혼자서는 안 짚고 딴 것과 겹쳐야 짚는 것."""
    것 = set()
    for 수 in _헷갈리는홑수:
        for 소리 in _소리들(수):
            읽기 = 소리 + "さい"
            if 읽기 not in 안쓰는나이말:
                것 |= {읽기, 가타카나로(읽기)}
    return frozenset(것)
